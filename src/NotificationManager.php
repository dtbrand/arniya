    /**
     * Safe variable substitution (supports {{variable}} and {variable})
     */
    public static function renderTemplate(string $templateText, array $variables): string
    {
        $rendered = $templateText;
        foreach ($variables as $k => $v) {
            $val = is_scalar($v) ? (string)$v : json_encode($v);
            // Replace both {{key}} and {key}
            $rendered = str_replace(["{{" . $k . "}}", "{" . $k . "}"], $val, $rendered);
        }
        return $rendered;
    }

