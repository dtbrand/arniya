     */
    public static function maskSecretsInJson(string $jsonStr): string
    {
        $arr = json_decode($jsonStr, true);
        if (!is_array($arr)) {
            return '{}';
        }

        $secretKeys = ['password', 'access_token', 'auth_key', 'server_key', 'api_secret', 'secret', 'token', 'private_key'];
        foreach ($arr as $k => $v) {
            if (in_array(strtolower($k), $secretKeys, true)) {
                $arr[$k] = '••••••••••••••••';
            }
        }
        return json_encode($arr);
    }

